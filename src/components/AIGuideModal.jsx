import React, { useState, useEffect } from 'react';
import { 
  X, Sparkles, Clock, MapPin, DollarSign, ShieldAlert, CheckCircle, 
  Copy, Check, Share2, Compass, Calendar, ChevronRight, Zap, CalendarDays 
} from 'lucide-react';
import { formatCurrency, formatPriceString } from '../utils/currency';

export default function AIGuideModal({ 
  isOpen,
  guide, 
  isLoading, 
  onClose, 
  currency = 'USD',
  onSaveToWishlist,
  isSaved,
  onChangeDays
}) {
  const [activeTab, setActiveTab] = useState('itinerary');
  const [selectedDayNumber, setSelectedDayNumber] = useState(1);
  const [copied, setCopied] = useState(false);

  // Close on Escape key
  useEffect(() => {
    if (!isOpen) return;
    const handleKeyDown = (e) => {
      if (e.key === 'Escape') {
        onClose();
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  // Reset selected day when guide updates
  useEffect(() => {
    setSelectedDayNumber(1);
  }, [guide?.destination, guide?.daysCount]);

  if (!isOpen) return null;

  const daysCount = guide?.daysCount || guide?.itineraryDays?.length || 1;
  const daySpendFormatted = formatCurrency(guide?.dailyBudgetUSD || 95, currency);
  const totalTripSpendFormatted = formatCurrency((guide?.dailyBudgetUSD || 95) * daysCount, currency);

  // Get active day data
  const currentDaysList = guide?.itineraryDays || (guide?.itinerary ? [{ dayNumber: 1, dayTitle: "Day 1 Highlights", slots: guide.itinerary }] : []);
  const activeDayData = currentDaysList.find(d => d.dayNumber === selectedDayNumber) || currentDaysList[0];

  const handleCopyMarkdown = () => {
    if (!guide) return;

    let itineraryMd = "";
    if (guide.itineraryDays && guide.itineraryDays.length > 0) {
      itineraryMd = guide.itineraryDays.map(d => {
        const slotsMd = d.slots.map(s => `  - **${s.period}**: ${s.activity} (${formatPriceString(s.cost, currency)})\n    *${s.description}*`).join('\n');
        return `### ${d.dayTitle}\n${slotsMd}`;
      }).join('\n\n');
    } else if (guide.itinerary) {
      itineraryMd = guide.itinerary.map(item => `### ${item.period}: ${item.activity} (${formatPriceString(item.cost, currency)})\n${item.description}`).join('\n\n');
    }

    const text = `# ${guide.destination}, ${guide.country} - WanderAI ${daysCount}-Day Travel Guide
**Tagline:** ${guide.tagline}
**Best Time to Visit:** ${guide.bestTimeToVisit}
**Trip Duration:** ${daysCount} Days
**Estimated Spend:** ~${daySpendFormatted}/day (~${totalTripSpendFormatted} total)

## ${daysCount}-Day Curated Itinerary
${itineraryMd}

## Top Must-See Attractions & Ticket Guide
${guide.topAttractions?.map(attr => `- **${attr.name}** | Fee: ${formatPriceString(attr.fee, currency)}\n  *Insider Tip:* ${attr.insiderTip}`).join('\n\n')}

## Budget Tiers
- **Backpacker:** ${formatPriceString(guide.budgetTiers?.backpacker, currency)}
- **Mid-Range:** ${formatPriceString(guide.budgetTiers?.midRange, currency)}
- **Luxury:** ${formatPriceString(guide.budgetTiers?.luxury, currency)}

## Local Etiquette & Traveler Tips
${guide.localTips?.map(tip => `- ${tip}`).join('\n')}

---
Generated by WanderAI - Firestorm Travel Platform`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const dayOptions = [1, 2, 3, 5, 7];

  return (
    <div 
      className="fixed inset-0 z-50 flex items-center justify-center p-2.5 sm:p-4 md:p-6 overflow-y-auto bg-slate-950/85 backdrop-blur-md animate-in fade-in duration-200 cursor-pointer"
      onClick={onClose}
    >
      <div 
        className="relative w-full max-w-4xl bg-slate-900 border border-slate-800 rounded-2xl sm:rounded-3xl shadow-2xl shadow-emerald-950/40 overflow-hidden flex flex-col max-h-[94vh] sm:max-h-[90vh] cursor-default my-auto"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="p-4 sm:p-6 border-b border-slate-800 bg-gradient-to-r from-slate-900 via-slate-900 to-slate-950 flex items-start justify-between gap-3">
          <div className="min-w-0 flex-1">
            <div className="flex items-center gap-2 mb-1 flex-wrap">
              <span className="flex items-center gap-1 px-2 sm:px-2.5 py-0.5 rounded-full text-[10px] sm:text-xs font-semibold bg-emerald-500/10 text-emerald-400 border border-emerald-500/30">
                <Sparkles className="w-3 h-3 sm:w-3.5 sm:h-3.5" />
                <span>{guide?.isLiveAI ? 'Live Gemini LLM' : 'WanderAI Engine'}</span>
              </span>
              <span className="px-2 py-0.5 rounded-full text-[10px] sm:text-xs font-bold bg-cyan-500/10 text-cyan-300 border border-cyan-500/30">
                {daysCount} Days Itinerary
              </span>
              {guide && (
                <span className="text-[11px] sm:text-xs text-slate-400 flex items-center gap-1">
                  <MapPin className="w-3 h-3 sm:w-3.5 sm:h-3.5 text-slate-500" />
                  {guide.country}
                </span>
              )}
            </div>

            <h2 className="text-xl sm:text-3xl font-extrabold text-white tracking-tight truncate">
              {isLoading ? "Consulting AI Engine..." : `${guide?.destination} (${daysCount} Days)`}
            </h2>

            {!isLoading && guide && (
              <p className="mt-1 text-xs sm:text-sm text-slate-400 max-w-2xl leading-relaxed line-clamp-2 sm:line-clamp-none">
                {guide.tagline}
              </p>
            )}
          </div>

          <button
            type="button"
            onClick={(e) => {
              e.stopPropagation();
              onClose();
            }}
            aria-label="Close modal"
            className="p-2 sm:p-2.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-400 hover:text-white transition cursor-pointer border border-slate-700/60 shadow-sm shrink-0"
            title="Close (Esc)"
          >
            <X className="w-4 h-4 sm:w-5 sm:h-5" />
          </button>
        </div>

        {/* Loading Spinner State */}
        {isLoading ? (
          <div className="p-12 sm:p-16 flex flex-col items-center justify-center text-center space-y-4">
            <div className="w-12 h-12 sm:w-14 sm:h-14 rounded-2xl bg-emerald-500/10 border border-emerald-500/30 flex items-center justify-center animate-spin">
              <Compass className="w-6 h-6 sm:w-8 h-8 text-emerald-400" />
            </div>
            <div>
              <p className="text-sm sm:text-base font-bold text-white">Synthesizing {daysCount}-Day Custom Plan...</p>
              <p className="text-xs text-slate-400 mt-1 max-w-sm px-4">
                Structuring daily pacing, ticket schedules, and optimal transit routes across {daysCount} days.
              </p>
            </div>
          </div>
        ) : (
          <>
            {/* Tab Navigation */}
            <div className="px-3 sm:px-6 border-b border-slate-800 bg-slate-950/40 flex items-center justify-between gap-2 overflow-x-auto text-xs font-medium no-scrollbar">
              <div className="flex items-center gap-1 sm:gap-2 shrink-0">
                {[
                  { id: 'itinerary', label: `${daysCount}-Day Itinerary` },
                  { id: 'attractions', label: 'Top Attractions & Fees' },
                  { id: 'budget', label: 'Budget Breakdown' },
                  { id: 'tips', label: 'Local Tips & Etiquette' }
                ].map(tab => (
                  <button
                    key={tab.id}
                    type="button"
                    onClick={() => setActiveTab(tab.id)}
                    className={`py-3 sm:py-3.5 px-2.5 sm:px-3 border-b-2 whitespace-nowrap transition cursor-pointer ${
                      activeTab === tab.id
                        ? 'border-emerald-400 text-emerald-400 font-bold'
                        : 'border-transparent text-slate-400 hover:text-slate-200'
                    }`}
                  >
                    {tab.label}
                  </button>
                ))}
              </div>

              {/* In-Modal Duration Switcher */}
              {onChangeDays && (
                <div className="flex items-center gap-1 pl-3 border-l border-slate-800/80 shrink-0 py-2">
                  <span className="text-[11px] text-slate-500 hidden sm:inline">Days:</span>
                  <div className="inline-flex bg-slate-900 border border-slate-800 rounded-lg p-0.5">
                    {dayOptions.map(d => (
                      <button
                        key={d}
                        type="button"
                        onClick={() => onChangeDays(d)}
                        className={`px-2 py-0.5 rounded text-[11px] font-semibold transition cursor-pointer ${
                          daysCount === d
                            ? 'bg-emerald-500 text-slate-950 font-bold'
                            : 'text-slate-400 hover:text-white'
                        }`}
                        title={`Switch to a ${d}-day plan`}
                      >
                        {d}D
                      </button>
                    ))}
                  </div>
                </div>
              )}
            </div>

            {/* Modal Body */}
            <div className="p-4 sm:p-6 overflow-y-auto space-y-5 sm:space-y-6 flex-1 text-slate-300">
              {/* Tab 1: Itinerary */}
              {activeTab === 'itinerary' && (
                <div className="space-y-4">
                  {/* Top Spend Summary */}
                  <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-3 border-b border-slate-800 text-xs gap-1.5 bg-slate-950/40 p-3 rounded-xl border border-slate-800/60">
                    <span className="text-slate-400">
                      Best Season: <strong className="text-white">{guide?.bestTimeToVisit?.split('.')[0]}</strong>
                    </span>
                    <div className="flex items-center gap-3">
                      <span className="text-slate-400">Daily: <strong className="text-emerald-400 font-mono font-medium">~{daySpendFormatted}</strong></span>
                      <span className="text-slate-400">Total ({daysCount}D): <strong className="text-cyan-400 font-mono font-bold">~{totalTripSpendFormatted}</strong></span>
                    </div>
                  </div>

                  {/* Day Navigation Tabs (when multiple days) */}
                  {currentDaysList.length > 1 && (
                    <div className="flex items-center gap-2 overflow-x-auto pb-1 no-scrollbar">
                      {currentDaysList.map((d) => (
                        <button
                          key={d.dayNumber}
                          type="button"
                          onClick={() => setSelectedDayNumber(d.dayNumber)}
                          className={`px-3 py-1.5 rounded-xl text-xs font-bold transition cursor-pointer shrink-0 border ${
                            selectedDayNumber === d.dayNumber
                              ? 'bg-emerald-500/20 text-emerald-400 border-emerald-500/50 shadow-sm'
                              : 'bg-slate-900 border-slate-800 text-slate-400 hover:text-white'
                          }`}
                        >
                          Day {d.dayNumber}
                        </button>
                      ))}
                    </div>
                  )}

                  {/* Active Day Title */}
                  <div className="pt-1">
                    <h3 className="text-sm sm:text-base font-bold text-white flex items-center gap-2">
                      <span className="w-6 h-6 rounded-lg bg-emerald-500/10 text-emerald-400 border border-emerald-500/30 flex items-center justify-center text-xs font-bold">
                        {activeDayData.dayNumber}
                      </span>
                      <span>{activeDayData.dayTitle}</span>
                    </h3>
                  </div>

                  {/* Day Slots Timeline */}
                  <div className="relative pl-5 sm:pl-6 space-y-4 sm:space-y-6 before:absolute before:left-1.5 sm:before:left-2 before:top-2 before:bottom-2 before:w-0.5 before:bg-slate-800">
                    {activeDayData.slots?.map((slot, idx) => (
                      <div key={idx} className="relative group">
                        <div className="absolute -left-5 sm:-left-6 top-1 w-3.5 h-3.5 sm:w-4 sm:h-4 rounded-full bg-slate-900 border-2 border-emerald-500 group-hover:scale-125 transition" />
                        <div className="bg-slate-950/60 border border-slate-800/80 rounded-xl sm:rounded-2xl p-3.5 sm:p-4 hover:border-slate-700 transition">
                          <div className="flex items-center justify-between gap-2 mb-1">
                            <span className="text-[11px] sm:text-xs font-bold text-emerald-400 flex items-center gap-1.5">
                              <Clock className="w-3 h-3 sm:w-3.5 sm:h-3.5 shrink-0" />
                              <span>{slot.period}</span>
                            </span>
                            <span className="text-xs font-mono font-semibold text-slate-300 bg-slate-800/60 px-2 py-0.5 rounded shrink-0">
                              {formatPriceString(slot.cost, currency)}
                            </span>
                          </div>
                          <h4 className="text-xs sm:text-sm font-bold text-white mb-1">{slot.activity}</h4>
                          <p className="text-[11px] sm:text-xs text-slate-400 leading-relaxed">{slot.description}</p>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Tab 2: Attractions */}
              {activeTab === 'attractions' && (
                <div className="space-y-3 sm:space-y-4">
                  <p className="text-xs text-slate-400">
                    Key landmarks and attractions with official entrance fee estimates and queue mitigation advice:
                  </p>
                  <div className="grid gap-2.5 sm:gap-3">
                    {guide?.topAttractions?.map((attr, idx) => (
                      <div key={idx} className="p-3.5 sm:p-4 rounded-xl sm:rounded-2xl bg-slate-950/60 border border-slate-800 flex flex-col sm:flex-row sm:items-center justify-between gap-2.5 sm:gap-3">
                        <div className="space-y-1">
                          <div className="flex items-center gap-2 flex-wrap">
                            <h4 className="text-xs sm:text-sm font-bold text-white">{attr.name}</h4>
                            <span className="text-[11px] sm:text-xs font-mono font-bold text-emerald-400 bg-emerald-500/10 px-2 py-0.5 rounded border border-emerald-500/20">
                              {formatPriceString(attr.fee, currency)}
                            </span>
                          </div>
                          <p className="text-[11px] sm:text-xs text-slate-400 flex items-start gap-1.5 pt-0.5 sm:pt-1">
                            <Zap className="w-3.5 h-3.5 text-amber-400 shrink-0 mt-0.5" />
                            <span><strong className="text-slate-300">Insider Tip:</strong> {attr.insiderTip}</span>
                          </p>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Tab 3: Budget Breakdown */}
              {activeTab === 'budget' && (
                <div className="space-y-4 sm:space-y-5">
                  <p className="text-xs text-slate-400">
                    Typical daily and total {daysCount}-day expenditures categorized by traveler style:
                  </p>
                  <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 sm:gap-4">
                    <div className="p-3.5 sm:p-4 rounded-xl sm:rounded-2xl bg-slate-950/60 border border-slate-800">
                      <span className="text-[10px] sm:text-[11px] font-bold text-emerald-400 uppercase tracking-wider">Backpacker</span>
                      <h4 className="text-sm sm:text-base font-extrabold text-white mt-1 mb-1.5 font-mono">
                        {formatPriceString(guide?.budgetTiers?.backpacker?.split(' ')[0], currency)}
                      </h4>
                      <p className="text-[11px] sm:text-xs text-slate-400 leading-relaxed">
                        {formatPriceString(guide?.budgetTiers?.backpacker, currency)}
                      </p>
                    </div>

                    <div className="p-3.5 sm:p-4 rounded-xl sm:rounded-2xl bg-slate-950/60 border border-emerald-500/30 relative shadow-lg shadow-emerald-950/20">
                      <div className="absolute top-3 right-3 text-[9px] sm:text-[10px] font-bold px-1.5 sm:px-2 py-0.5 rounded bg-emerald-500 text-slate-950">
                        POPULAR
                      </div>
                      <span className="text-[10px] sm:text-[11px] font-bold text-teal-400 uppercase tracking-wider">Mid-Range</span>
                      <h4 className="text-sm sm:text-base font-extrabold text-white mt-1 mb-1.5 font-mono">
                        {formatPriceString(guide?.budgetTiers?.midRange?.split(' ')[0], currency)}
                      </h4>
                      <p className="text-[11px] sm:text-xs text-slate-400 leading-relaxed">
                        {formatPriceString(guide?.budgetTiers?.midRange, currency)}
                      </p>
                    </div>

                    <div className="p-3.5 sm:p-4 rounded-xl sm:rounded-2xl bg-slate-950/60 border border-slate-800">
                      <span className="text-[10px] sm:text-[11px] font-bold text-purple-400 uppercase tracking-wider">Luxury</span>
                      <h4 className="text-sm sm:text-base font-extrabold text-white mt-1 mb-1.5 font-mono">
                        {formatPriceString(guide?.budgetTiers?.luxury?.split(' ')[0], currency)}
                      </h4>
                      <p className="text-[11px] sm:text-xs text-slate-400 leading-relaxed">
                        {formatPriceString(guide?.budgetTiers?.luxury, currency)}
                      </p>
                    </div>
                  </div>
                </div>
              )}

              {/* Tab 4: Local Tips */}
              {activeTab === 'tips' && (
                <div className="space-y-3 sm:space-y-4">
                  <p className="text-xs text-slate-400">
                    Essential practical advice for seamless navigation and cultural awareness:
                  </p>
                  <div className="space-y-2.5 sm:space-y-3">
                    {guide?.localTips?.map((tip, idx) => (
                      <div key={idx} className="p-3 sm:p-3.5 rounded-xl bg-slate-950/60 border border-slate-800 flex items-start gap-2.5 sm:gap-3">
                        <CheckCircle className="w-4 h-4 text-emerald-400 shrink-0 mt-0.5" />
                        <span className="text-[11px] sm:text-xs text-slate-300 leading-relaxed">{tip}</span>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>

            {/* Footer with Actions */}
            <div className="p-3 sm:p-5 border-t border-slate-800 bg-slate-950/80 flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-2.5 text-xs">
              <button
                type="button"
                onClick={handleCopyMarkdown}
                className="flex items-center justify-center gap-1.5 px-3.5 py-2.5 sm:py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white transition font-medium cursor-pointer w-full sm:w-auto"
              >
                {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
                <span>{copied ? "Copied Guide!" : `Copy ${daysCount}-Day Plan`}</span>
              </button>

              <div className="flex items-center gap-2 w-full sm:w-auto">
                <button
                  type="button"
                  onClick={onClose}
                  className="flex-1 sm:flex-none px-4 py-2.5 sm:py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white font-medium transition cursor-pointer text-center"
                >
                  Close
                </button>
                <button
                  type="button"
                  onClick={() => onSaveToWishlist(guide)}
                  className={`flex-1 sm:flex-none flex items-center justify-center gap-1.5 px-4 py-2.5 sm:py-2 rounded-xl font-bold transition cursor-pointer ${
                    isSaved
                      ? 'bg-rose-500/10 text-rose-400 border border-rose-500/30'
                      : 'bg-emerald-500 hover:bg-emerald-400 text-slate-950 shadow-md shadow-emerald-500/20'
                  }`}
                >
                  <Check className="w-4 h-4" />
                  <span>{isSaved ? "Saved in Wishlist" : `Save ${daysCount}-Day Plan`}</span>
                </button>
              </div>
            </div>
          </>
        )}
      </div>
    </div>
  );
}
